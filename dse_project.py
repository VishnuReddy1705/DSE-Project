import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder, StandardScaler, OneHotEncoder
from sklearn.impute import SimpleImputer
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.neighbors import KNeighborsClassifier
from sklearn.decomposition import PCA
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
    confusion_matrix,
    classification_report
)
# 1. Load Dataset
file_path = "Cleaned_Datasets/03_repayment_history_6000_cleaned.csv"
df = pd.read_csv(file_path)
print("========== KNN CLASSIFICATION ==========")
print("\nDataset Loaded Successfully!")
print("Dataset Shape:", df.shape)
# 2. Select Target Column
possible_targets = [
    "Payment_Status",
    "Repayment_Status",
    "Loan_Status",
    "Payment_Result",
    "Repayment_Result",
    "Default_Status",
    "Payment_Delay_Status"
]
target_column = next(
    (col for col in possible_targets if col in df.columns),
    None
)
if target_column is None:
    print("\nAvailable Dataset Columns:")
    print(df.columns.tolist())
    raise ValueError(
        "\nNo recognized target column found. "
        "Please set target_column to the correct repayment "
        "outcome column in your dataset."
    )
print("\nSelected Target Column:", target_column)
# Remove missing target rows
df = df.dropna(subset=[target_column]).copy()
# Separate features and target
X = df.drop(columns=[target_column])
y = df[target_column].astype(str).str.strip()
# 3. Remove ID and Unnecessary Columns
id_columns = [
    col for col in X.columns
    if any(word in col.lower() for word in [
        "id",
        "phone",
        "mobile",
        "account_number"
    ])
]
X = X.drop(columns=id_columns, errors="ignore")
# Remove constant columns
constant_columns = [
    col for col in X.columns
    if X[col].nunique(dropna=False) <= 1
]
X = X.drop(columns=constant_columns, errors="ignore")
print("\nRemoved ID Columns:", id_columns)
# Encode target labels
label_encoder = LabelEncoder()
y = label_encoder.fit_transform(y)
print("Target Classes:", list(label_encoder.classes_))
# 4. Identify Numeric and Categorical Features
numeric_columns = X.select_dtypes(
    include=["int64", "float64"]
).columns.tolist()
categorical_columns = X.select_dtypes(
    exclude=["int64", "float64"]
).columns.tolist()
print("\nNumeric Features:", numeric_columns)
print("Categorical Features:", categorical_columns)
# 5. Data Preprocessing
# Numeric data: Missing value treatment + scaling
numeric_transformer = Pipeline(steps=[
    ("imputer", SimpleImputer(strategy="median")),
    ("scaler", StandardScaler())
])
# Categorical data: Missing value treatment + encoding
categorical_transformer = Pipeline(steps=[
    ("imputer", SimpleImputer(strategy="most_frequent")),
    ("encoder", OneHotEncoder(handle_unknown="ignore"))
])
preprocessor = ColumnTransformer(transformers=[
    ("num", numeric_transformer, numeric_columns),
    ("cat", categorical_transformer, categorical_columns)
])
# 6. Create KNN Model
model = Pipeline(steps=[
    ("preprocessor", preprocessor),
    ("classifier", KNeighborsClassifier(
        n_neighbors=5,
        weights="distance",
        metric="minkowski",
        p=2
    ))
])
# 7. Split Dataset
class_counts = np.bincount(y)
stratify_option = (
    y if len(class_counts) > 1 and np.min(class_counts) >= 2
    else None
)
X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=stratify_option
)
print("\nTraining Records:", len(X_train))
print("Testing Records:", len(X_test))
# 8. Train KNN Model
model.fit(X_train, y_train)
print("\nKNN Model Trained Successfully!")
# 9. Make Predictions
y_pred = model.predict(X_test)
# 10. Calculate Performance Metrics
accuracy = accuracy_score(y_test, y_pred)
precision = precision_score(
    y_test,
    y_pred,
    average="weighted",
    zero_division=0
)
recall = recall_score(
    y_test,
    y_pred,
    average="weighted",
    zero_division=0
)

f1 = f1_score(
    y_test,
    y_pred,
    average="weighted",
    zero_division=0
)
print("\n========== MODEL PERFORMANCE ==========")
print(f"Accuracy  : {accuracy * 100:.2f}%")
print(f"Precision : {precision * 100:.2f}%")
print(f"Recall    : {recall * 100:.2f}%")
print(f"F1 Score  : {f1 * 100:.2f}%")
# 11. ROC-AUC Score
if len(label_encoder.classes_) == 2:
    y_probability = model.predict_proba(X_test)[:, 1]
    roc_auc = roc_auc_score(y_test, y_probability)
    print(f"ROC-AUC   : {roc_auc:.4f}")
else:
    print("ROC-AUC   : Not calculated (multiclass dataset)")
# 12. Confusion Matrix
cm = confusion_matrix(y_test, y_pred)
print("\n========== CONFUSION MATRIX ==========")
print(cm)
# 13. Classification Report
print("\n========== CLASSIFICATION REPORT ==========")
print(classification_report(
    y_test,
    y_pred,
    labels=np.arange(len(label_encoder.classes_)),
    target_names=label_encoder.classes_,
    zero_division=0
))
